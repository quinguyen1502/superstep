// Socket types come from the same JSON Schemas the backend contract tests validate.
import { readFileSync, writeFileSync } from 'node:fs'
import openapiTS, { astToString } from 'openapi-typescript'

const schemas = {}, unions = {}, roots = {}
for (const side of ['client', 'server']) {
  const source = JSON.parse(readFileSync(new URL(`../../../backend/app/api/schemas/chat_ws_v1/${side}.json`, import.meta.url), 'utf8'))
  const prefix = side === 'client' ? 'Client' : 'Server'
  const name = value => prefix + value.split('_').map(part => part[0].toUpperCase() + part.slice(1)).join('')
  const rewrite = value => {
    if (Array.isArray(value)) return value.map(rewrite)
    if (!value || typeof value !== 'object') return value
    const out = Object.fromEntries(Object.entries(value).map(([key, item]) => [key, key === '$ref' ? `#/components/schemas/${name(item.split('/').pop())}` : rewrite(item)]))
    // JSON Schema's plain object (including form responses) is open unless explicitly closed.
    if ((value.type === 'object' || value.type?.includes?.('object')) && !value.properties && value.additionalProperties === undefined) out.additionalProperties = true
    return out
  }
  for (const [key, value] of Object.entries(source.$defs)) {
    // Server variants inherit required `type` from base; make that intersection explicit for OpenAPI's generator.
    const definition = value.properties?.type?.const ? { ...value, required: [...new Set([...(value.required ?? []), 'type'])] } : value
    schemas[name(key)] = rewrite(definition)
  }
  roots[side] = source
  unions[prefix + 'Frame'] = source.oneOf.map(ref => `components['schemas']['${name(ref.$ref.split('/').pop())}']`).join(' | ')
}
const ast = await openapiTS({ openapi: '3.1.0', info: { title: 'Chat socket v1', version: '1' }, paths: {}, components: { schemas } })
let output = '// Generated by npm run gen:chat from backend/app/api/schemas/chat_ws_v1. Do not edit.\n' + astToString(ast)
for (const [name, value] of Object.entries(unions)) output += `\nexport type ${name} = ${value}\n`
output += `\nexport const SERVER_TYPES = ${JSON.stringify(roots.server.oneOf.map(ref => roots.server.$defs[ref.$ref.split('/').pop()].properties.type.const))} as const\n`
output += `export const DONE_STATUSES = ${JSON.stringify(roots.server.$defs.done.properties.status.enum)} as const\n`
const file = new URL('../src/chat/frames.ts', import.meta.url)
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== output) { console.error('Chat socket types are stale: run npm run gen:chat.'); process.exitCode = 1 }
} else writeFileSync(file, output)
