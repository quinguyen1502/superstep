// Prepends a "generated" header to src/schema.ts (written by `npm run gen` from docs/api/openapi.public.json).
import { readFileSync, writeFileSync } from 'node:fs'
const file = new URL('../src/schema.ts', import.meta.url)
const HEADER = '// Generated by `npm run gen` from docs/api/openapi.public.json (openapi-typescript). Do not edit.\n'
const text = readFileSync(file, 'utf8')
if (!text.startsWith(HEADER)) writeFileSync(file, HEADER + text)
