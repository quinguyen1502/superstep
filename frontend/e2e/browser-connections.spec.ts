import { test, expect, type Page } from '@playwright/test'
import { login } from './helpers'
import en from '../src/locales/en.json' with { type: 'json' }
import vi from '../src/locales/vi.json' with { type: 'json' }

async function choose(page: Page, id: string, name: string) {
  await page.locator(`#${id}`).click()
  await page.getByRole('option', { name, exact: true }).click()
}

test('remote browser: encrypted controller edit, operator route and disabled capability', async ({ page }) => {
  const headers = await login(page)
  await page.evaluate(() => localStorage.setItem('lang', 'en'))
  await page.goto('/settings/mcp'); await page.locator('#mcp-add').click()
  await page.locator('#mcp-new-name').fill('Remote fixture')
  await choose(page, 'mcp-new-transport', en.managedTools.transport)
  await choose(page, 'mcp-new-adapter', en.managedTools.adapters.browser)
  await choose(page, 'mcp-new-scope', en.approvals.scope.org)
  await expect(page.locator('#mcp-new-profile-enabled')).toBeDisabled()
  await choose(page, 'mcp-new-scope', en.approvals.scope.user)
  await choose(page, 'mcp-new-provider', en.browserSettings.providers.browserless)
  await page.locator('#mcp-new-allowed_origins').fill('https://example.org')
  await page.locator('#mcp-new-browserless_token').fill('short')
  await page.locator('#mcp-create').click()
  await expect(page.locator('#mcp-new-browserless_token-error')).toHaveText(en.browserSettings.errors.token)
  await page.locator('#mcp-new-browserless_token').fill('synthetic-browserless-token-for-ui-fixture')
  await choose(page, 'mcp-new-proxy_mode', en.browserSettings.proxyModes.operator_default)
  await page.locator('#mcp-create').click()
  const card = page.locator('[data-testid^="mcp-card-"]', { hasText: 'Remote fixture' })
  await expect(card).toBeVisible(); await card.locator('[id$="-discover"]').click()
  await expect(card.getByTestId('mcp-tools')).toContainText('navigate')
  await card.locator('[id$="-edit"]').click()
  await expect(card.locator('[id$="-browserless_token"]')).toHaveValue('')
  await card.getByRole('button', { name: en.common.save, exact: true }).click()
  await expect(card).toContainText(en.mcp.saved)
  const body = await (await page.request.get('/api/mcp/servers', { headers })).json()
  expect(JSON.stringify(body)).not.toContain('synthetic-browserless-token')
  // Operator feature metadata disappearing must disable editing the stored adapter.
  await page.route('**/api/mcp/servers', async route => {
    const response = await route.fetch(), value = await response.json()
    value.data.managed_adapters = value.data.managed_adapters.filter((item: { id: string }) => item.id !== 'browser')
    await route.fulfill({ response, json: value })
  })
  await page.reload()
  const disabled = page.locator('[data-testid^="mcp-card-"]', { hasText: 'Remote fixture' })
  await disabled.locator('[id$="-edit"]').click()
  await expect(disabled).toContainText(en.browserSettings.disabled)
  await expect(disabled.locator('[id$="-provider"]')).toBeDisabled()
  await expect(disabled.locator('[id$="-delete"]')).toBeEnabled()
})
async function confirmName(page: Page, name: string) {
  await expect(page.locator('#confirm-delete-submit')).toBeDisabled()
  await page.locator('#confirm-delete-input').fill(`${name}-wrong`)
  await expect(page.locator('#confirm-delete-submit')).toBeDisabled()
  await page.locator('#confirm-delete-input').fill(name)
  await page.locator('#confirm-delete-submit').click()
  await expect(page.getByRole('alertdialog')).toHaveCount(0)
}

for (const lang of ['en', 'vi'] as const) for (const theme of ['light', 'dark'] as const) {
  test(`browser connection: proxy, profile, stored secrets and web separation (${lang}, ${theme})`, async ({ page, request }) => {
    test.setTimeout(120_000)
    const t = lang === 'en' ? en : vi, headers = await login(page), suffix = `${lang}-${theme}`, name = `Browser ${suffix}`
    await page.setViewportSize({ width: 1280, height: 1100 })
    await page.evaluate(([l, mode]) => { localStorage.setItem('lang', l); localStorage.setItem('theme', mode) }, [lang, theme])
    await page.goto('/settings/mcp'); await page.locator('#mcp-add').click()
    await page.locator('#mcp-new-name').fill(name)
    await choose(page, 'mcp-new-transport', t.managedTools.transport)
    await choose(page, 'mcp-new-adapter', t.managedTools.adapters.browser)
    await expect(page.locator('#mcp-new-browser-settings')).toContainText(t.browserSettings.connectionHelp)
    // Required whitelist (DEC-0085) must be valid so proxy is the focused first error.
    await page.locator('#mcp-new-allowed_origins').fill('https://example.org')
    await choose(page, 'mcp-new-proxy_mode', t.browserSettings.proxyModes.custom)
    await page.locator('#mcp-new-proxy_server').fill('socks5://proxy.example.org:1080')
    await page.locator('#mcp-create').click()
    await expect(page.locator('#mcp-new-proxy_server')).toBeFocused()
    await expect(page.locator('#mcp-new-proxy_server-error')).toHaveText(t.browserSettings.errors.proxy)
    await page.locator('#mcp-new-proxy_server').fill('http://proxy.example.org:3128')
    await choose(page, 'mcp-new-proxy_auth', t.browserSettings.auth.basic)
    await page.locator('#mcp-new-proxy_username').fill('synthetic-proxy-user')
    await page.locator('#mcp-new-proxy_password').fill('synthetic-proxy-password')
    await page.locator('#mcp-new-profile-enabled').click()
    await page.locator('#mcp-new-profile_name').fill('personal-fixture')
    await page.locator('#mcp-new-profile_origins').fill('https://example.org')
    await page.locator('#mcp-new-profile_state').fill('{"cookies":[],"origins":[]}')
    // Provider drafts survive switching; only the chosen provider is submitted.
    await choose(page, 'mcp-new-provider', t.browserSettings.providers.browserless)
    await page.locator('#mcp-new-browserless_token').fill('synthetic-browserless-token-for-ui-fixture')
    await choose(page, 'mcp-new-provider', t.browserSettings.providers.local)
    await choose(page, 'mcp-new-provider', t.browserSettings.providers.browserless)
    await expect(page.locator('#mcp-new-browserless_token')).toHaveValue('synthetic-browserless-token-for-ui-fixture')
    await choose(page, 'mcp-new-provider', t.browserSettings.providers.local)
    await page.getByRole('button', { name: t.browserSettings.resources, exact: true }).click()
    await page.locator('#mcp-new-lifetime_s').fill('120'); await page.locator('#mcp-create').click()
    await expect(page.locator('#mcp-new-idle_timeout_s-error')).toHaveText(t.browserSettings.errors.idleLifetime)
    await page.locator('#mcp-new-lifetime_s').fill('3600')
    if (process.env.REVIEW_SHOTS) await page.locator('#mcp-new').screenshot({ path: `${process.env.REVIEW_SHOTS}/browser-settings-${suffix}.png` })
    await page.locator('#mcp-create').click()
    const card = page.locator('[data-testid^="mcp-card-"]', { hasText: name })
    await expect(card).toBeVisible()
    const response = await page.request.get('/api/mcp/servers', { headers }), body = await response.json()
    const server = body.data.servers.find((item: { name: string }) => item.name === name), idp = `mcp-${server.id}`
    expect(server.settings.provider).toBe('local'); expect(server.secrets.browserless_token).toBeUndefined()
    expect(JSON.stringify(body)).not.toContain('synthetic-proxy-password')
    expect((await request.get('/api/mcp/servers')).status()).toBe(401)
    await card.locator('[id$="-discover"]').click()
    await expect(card.getByTestId('mcp-tools')).toContainText('navigate')
    await card.locator('[id$="-edit"]').click()
    await expect(page.locator(`#${idp}-proxy_password`)).toHaveValue('')
    await expect(page.locator(`#${idp}-profile_state`)).toHaveValue('')
    await card.getByRole('button', { name: t.common.save, exact: true }).click()
    await expect(card).toContainText(t.mcp.saved)
    // Explicit clearing and profile removal both require the shared exact-name dialog.
    await page.locator(`#${idp}-proxy_password-clear`).click(); await confirmName(page, 'proxy_password')
    await card.getByRole('button', { name: t.common.save, exact: true }).click()
    await expect(page.locator(`#${idp}-proxy_password-error`)).toBeVisible()
    await page.locator(`#${idp}-proxy_password`).fill('synthetic-replacement-password')
    await page.locator(`#${idp}-profile-remove`).click(); await confirmName(page, 'personal-fixture')
    await expect(page.locator(`#${idp}-profile-enabled`)).toHaveAttribute('aria-checked', 'false')
    await card.getByRole('button', { name: t.common.save, exact: true }).click()
    await expect(card).toContainText(t.mcp.saved)
    await page.setViewportSize({ width: 390, height: 844 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.locator(`#${idp}-proxy_server`).focus(); await page.keyboard.press('Tab')
    await expect(page.locator(`#${idp}-proxy_auth`)).toBeFocused()
    if (process.env.REVIEW_SHOTS) await page.screenshot({ path: `${process.env.REVIEW_SHOTS}/browser-settings-narrow-${suffix}.png`, fullPage: true })
    await card.locator('[id$="-delete"]').click(); await confirmName(page, name)
    await expect(card).toHaveCount(0)
    await page.setViewportSize({ width: 1280, height: 1100 })
    await page.locator('#mcp-add').click(); await page.locator('#mcp-new-name').fill(`Web ${suffix}`)
    await choose(page, 'mcp-new-transport', t.managedTools.transport)
    await choose(page, 'mcp-new-adapter', t.managedTools.adapters.web)
    await expect(page.locator('#mcp-new-proxy_mode')).toHaveCount(0)
    await page.locator('#mcp-new-enable-search').click(); await page.locator('#mcp-create').click()
    await expect(page.locator('#mcp-new-search_endpoint-error')).toHaveText(t.browserSettings.errors.searchEndpoint)
    await page.locator('#mcp-new-search_endpoint').fill('https://search.example.org/search')
    await page.locator('#mcp-new-search_headers').fill('{"Authorization":"Bearer synthetic-search-key"}')
    if (process.env.REVIEW_SHOTS) await page.locator('#mcp-new').screenshot({ path: `${process.env.REVIEW_SHOTS}/web-settings-${suffix}.png` })
    await page.locator('#mcp-create').click()
    const web = page.locator('[data-testid^="mcp-card-"]', { hasText: `Web ${suffix}` })
    await expect(web).toBeVisible(); await web.locator('[id$="-discover"]').click()
    await expect(web.getByTestId('mcp-tools')).toContainText('search'); await expect(web.getByTestId('mcp-tools')).toContainText('fetch')
    await web.locator('[id$="-edit"]').click(); await expect(web.locator('[id$="-search_headers"]')).toHaveValue('')
  })
}
