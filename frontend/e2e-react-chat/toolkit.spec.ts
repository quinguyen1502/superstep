import { test, expect } from '@playwright/test'
import { expectRowAligned } from '../e2e/helpers/alignment'
import { vt } from '../e2e/catalog'

test('built toolkit: theme/locale isolation, Human answer, files, feedback and identity', async ({ page }, info) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error' && !message.text().includes('Failed to load resource')) errors.push(message.text()) })
  await page.goto('/react/')
  await expect(page.locator('main')).toHaveAttribute('data-react-version', process.env.REACT_COMPAT_ROOT ? /^18\./ : /^19\./)
  const host = page.locator('#host-sentinel')
  const before = await host.evaluate(element => { const s = getComputedStyle(element); return [s.fontFamily, s.fontSize, s.padding, s.borderWidth, s.borderRadius] })
  expect(before).toEqual(['Georgia, serif', '15px', '12px', '2px', '8px'])
  await page.getByTestId('signin-lan').click()
  const chat = page.getByTestId('main-chat'), composed = page.getByTestId('composed-chat')
  await expect(chat.getByRole('textbox')).toBeEnabled()
  await expect(composed.getByRole('textbox', { name: vt('chat.message') })).toBeEnabled()
  const capture = async (name: string) => {
    await expect.poll(() => chat.locator('.superstep-chat').evaluate(el => [...el.querySelectorAll('header button, textarea')]
      .every(control => getComputedStyle(control).color === getComputedStyle(el).color))).toBe(true)
    const file = info.outputPath(`${name}.png`)
    await page.screenshot({ path: file, fullPage: true, animations: 'disabled' })
    await info.attach(name, { path: file, contentType: 'image/png' })
  }
  const inputGroup = chat.locator('[data-slot=input-group]')
  const lightBackground = await inputGroup.evaluate(element => getComputedStyle(element).backgroundColor)
  await page.evaluate(() => { document.documentElement.dataset.colorScheme = 'dark' })
  await expect(inputGroup).toHaveCSS('background-color', lightBackground)
  await page.evaluate(() => { delete document.documentElement.dataset.colorScheme })
  await expectRowAligned(await page.locator('.host-controls button').all())
  await expectRowAligned(await chat.locator('header button').all())
  await capture('react-light')
  await page.getByRole('button', { name: 'Dark', exact: true }).click()
  await expect(chat.locator('.superstep-chat')).toHaveAttribute('data-color-scheme', 'dark')
  await expectRowAligned(await chat.locator('header button').all())
  await capture('react-dark')
  await page.getByRole('button', { name: 'Custom theme', exact: true }).click()
  await expect(chat.locator('.superstep-chat')).toHaveCSS('font-family', 'Georgia, serif')
  await chat.locator('input[type=file]').setInputFiles({ name: 'sample-note.txt', mimeType: 'text/plain', buffer: Buffer.from('A sample toolkit attachment') })
  await expect(chat.getByTestId('chat-file')).toHaveAttribute('data-state', 'done')
  await chat.getByRole('textbox', { name: 'Message', exact: true }).fill('Please review this toolkit request')
  await chat.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(chat.getByTestId('question-card')).toBeVisible()
  await chat.getByRole('button', { name: 'Approve', exact: true }).click()
  await expect(chat.getByTestId('chat-answer').last()).toHaveAttribute('data-status', 'ok')
  await expect(chat.getByTestId('chat-turn-file').first()).toContainText('sample-note.txt')
  const download = page.waitForEvent('download')
  await chat.getByTestId('chat-file-download').first().click()
  expect((await download).suggestedFilename()).toBe('sample-note.txt')
  await chat.getByTestId('chat-rate-up').last().click()
  await expect(chat.getByTestId('chat-rate-up').last()).toHaveAttribute('aria-pressed', 'true')
  await capture('react-custom')
  await chat.getByTestId('chat-rate-up').last().click()
  const dialog = chat.getByRole('alertdialog'), remove = dialog.getByRole('button', { name: 'Delete' })
  await expect(remove).toBeDisabled()
  await dialog.getByRole('textbox').fill('Rating'); await remove.click()
  await expect(dialog).not.toBeVisible()
  await expect(chat.getByTestId('chat-rate-up').last()).toHaveAttribute('aria-pressed', 'false')
  const original = 'Please review this toolkit request'
  await chat.getByRole('button', { name: 'Edit message', exact: true }).click()
  const editDialog = chat.getByRole('alertdialog')
  await expect(editDialog).toContainText('API calls, writes and notifications may repeat')
  await editDialog.getByRole('textbox').fill('Edited toolkit request')
  await capture('react-edit-confirm-en-dark')
  await editDialog.getByRole('button', { name: 'Save and run in new branch' }).click()
  await expect(chat.getByTestId('question-card')).toBeVisible()
  await chat.getByRole('button', { name: 'Approve', exact: true }).click()
  await expect(chat.getByTestId('chat-answer').last()).toHaveAttribute('data-status', 'ok')
  await expect(chat.getByTestId('chat-mine').first().locator('[data-slot=bubble-content]')).toHaveText('Edited toolkit request')
  await expect(chat.getByTestId('chat-turn-file').first()).toContainText('sample-note.txt')
  await chat.getByRole('button', { name: 'Original conversation' }).click()
  await expect(chat.getByTestId('chat-mine').first().locator('[data-slot=bubble-content]')).toHaveText(original)
  await chat.getByRole('button', { name: 'Regenerate answer', exact: true }).click()
  const regenerateDialog = chat.getByRole('alertdialog')
  await expect(regenerateDialog.getByRole('textbox')).toHaveCount(0)
  await capture('react-regenerate-confirm-en-custom')
  await regenerateDialog.getByRole('button', { name: 'Run again in new branch' }).click()
  await expect(chat.getByTestId('question-card')).toBeVisible()
  await expect(chat.getByTestId('chat-turn-file').first()).toContainText('sample-note.txt')
  await chat.getByRole('button', { name: 'Approve', exact: true }).click()
  await expect(chat.getByTestId('chat-answer').last()).toHaveAttribute('data-status', 'ok')
  await expect(chat.getByTestId('chat-mine').first().locator('[data-slot=bubble-content]')).toHaveText(original)
  await chat.getByRole('button', { name: 'Original conversation' }).click()
  await expect(chat.getByTestId('chat-mine')).toHaveCount(2)
  await expectRowAligned(await chat.locator('header button').all())
  await chat.getByRole('combobox').click()
  await expect(chat.getByRole('listbox')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Vietnamese', exact: true }).click()
  await expect(chat.getByRole('textbox', { name: vt('chat.message'), exact: true })).toBeEnabled()
  await expect(composed.getByRole('textbox', { name: 'Message', exact: true })).toBeEnabled()
  await expectRowAligned(await chat.locator('header button').all())
  await page.getByTestId('signin-minh').click()
  await expect(chat.getByRole('textbox', { name: vt('chat.message'), exact: true })).toBeEnabled()
  await expect(chat).not.toContainText('Please review this toolkit request')
  const after = await host.evaluate(element => { const s = getComputedStyle(element); return [s.fontFamily, s.fontSize, s.padding, s.borderWidth, s.borderRadius] })
  expect(after).toEqual(before)
  expect(errors).toEqual([])
})
